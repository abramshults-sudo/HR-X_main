export function findRoleOption(title: string): RoleOption | undefined {
  for (const group of targetRoleGroups) {
    const role = group.roles.find(r => r.title === title);
    if (role) return role;
  }
  for (const group of experiencedRoleGroups) {
    const role = group.roles.find(r => r.title === title);
    if (role) return role;
  }
  return undefined;
}

